const fs = require("fs"), assert = require("assert");
const { chromium } = require("../.crm-test/tools/node_modules/playwright");
(async () => {
  const fixture = JSON.parse(fs.readFileSync(".crm-test/browser.json", "utf8"));
  if (!fixture.host.endsWith(".localhost")) throw Error("Only local fixtures are allowed");
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: "__session", value: fixture.sessions.agent, domain: fixture.host, path: "/" }]);
  const page = await context.newPage();
  await page.goto(`http://${fixture.host}:3107/student-dashboard/crm`);
  await page.getByRole("button", { name: "Training Customers", exact: true }).click();
  await page.getByText("Page 1 · 100 training customers", { exact: true }).waitFor();
  await page.getByLabel("Search training customers").fill("00020000002");
  await page.locator("main form").getByRole("button", { name: "Search", exact: true }).click();
  await page.getByText("Page 1 · 1 training customers", { exact: true }).waitFor();
  await page.getByRole("button", { name: "Use customer", exact: true }).click();
  assert.equal(await page.getByLabel("Calling number", { exact: true }).inputValue(), "00010000002");
  await page.getByLabel("Calling number", { exact: true }).fill("");
  await page.getByLabel("Issue details", { exact: true }).fill("Keep my draft complaint description");
  await page.getByRole("button", { name: "Fetch Data by registered number", exact: true }).click();
  await page.getByRole("status").filter({ hasText: "training customer TRAIN-002" }).waitFor();
  assert.equal(await page.getByLabel("Calling number", { exact: true }).inputValue(), "00010000002");
  assert.equal(await page.getByLabel("Registered number", { exact: true }).inputValue(), "00020000002");
  assert.equal(await page.getByLabel("Issue details", { exact: true }).inputValue(), "Keep my draft complaint description");
  const saved = page.waitForResponse((r) => r.url().includes("/api/crm") && r.request().method() === "POST");
  await page.getByRole("button", { name: "Save as Pending", exact: true }).click();
  const complaint = await (await saved).json(); assert(complaint.id, complaint.error);
  await page.getByRole("heading", { name: complaint.code }).waitFor();
  await page.getByRole("button", { name: "New Complaint", exact: true }).click();
  await page.getByLabel("Registered number", { exact: true }).fill("00020000002");
  await page.getByRole("button", { name: "Fetch Data by registered number", exact: true }).click();
  await page.getByRole("status").filter({ hasText: `complaint ${complaint.code}` }).waitFor();
  await page.getByRole("button", { name: "Fetch Data by calling number", exact: true }).click();
  await page.getByRole("status").filter({ hasText: `complaint ${complaint.code}` }).waitFor();
  await page.screenshot({ path: ".crm-test/training-fetch.png", fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  assert(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), "Mobile fetch form overflow");
  await browser.close();
  console.log("PASS: 100-customer directory, registered search, both fetch buttons, draft preservation, new complaint and latest-history preference, mobile width.");
})().catch((e) => { console.error(e.message); process.exit(1); });
