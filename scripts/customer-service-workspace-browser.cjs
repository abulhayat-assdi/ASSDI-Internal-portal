const fs = require("fs"), assert = require("assert"), { randomUUID } = require("crypto");
const { chromium } = require("../.crm-test/tools/node_modules/playwright");
Object.assign(process.env, JSON.parse(fs.readFileSync(".crm-test/env.json", "utf8")));
for (const key of ["DATABASE_URL", "CUSTOMER_SERVICE_DATABASE_URL"]) {
  const u = new URL(process.env[key]);
  if (u.hostname !== "127.0.0.1" || u.port !== "55439" || !u.pathname.endsWith("_test")) throw Error("Only local fixtures are allowed");
}
(async () => {
  const fixture = JSON.parse(fs.readFileSync(".crm-test/browser.json", "utf8"));
  assert(fixture.host.endsWith(".localhost"));
  const { PrismaClient } = require("@prisma/client");
  const portal = new PrismaClient();
  const course = await portal.course.findUnique({ where: { slug: fixture.host.replace(".localhost", "") } });
  const batch = await portal.batch.create({ data: { courseId: course.id, name: "Workspace browser " + randomUUID().slice(0, 8) } });
  await portal.$disconnect();
  const browser = await chromium.launch();
  const context = await browser.newContext({ viewport: { width: 1440, height: 1000 } });
  await context.addCookies([{ name: "__session", value: fixture.sessions.admin, domain: fixture.host, path: "/" }]);
  const page = await context.newPage();
  const base = `http://${fixture.host}:3107/dashboard/crm`;
  await page.goto(base + "/settings");
  await page.getByRole("heading", { name: "SLA policies", exact: true }).waitFor();
  assert.equal(await page.getByText("Provision a batch workspace", { exact: true }).count(), 0);
  await page.getByLabel("Workspace", { exact: true }).selectOption("batch:" + batch.id);
  await page.getByRole("heading", { name: "Administration · " + batch.name, exact: true }).waitFor();
  const selected = await page.getByLabel("Workspace", { exact: true }).inputValue();
  await page.getByRole("button", { name: "Training Customers", exact: true }).click();
  await page.getByText("Page 1 · 100 training customers", { exact: true }).waitFor();
  assert.equal(new URL(page.url()).searchParams.get("view"), "training-customers");
  assert.equal(new URL(page.url()).pathname, "/dashboard/crm");
  await page.reload();
  await page.getByText("Page 1 · 100 training customers", { exact: true }).waitFor();
  assert.equal(await page.getByLabel("Workspace", { exact: true }).inputValue(), selected);
  await page.getByRole("button", { name: "New Complaint", exact: true }).click();
  await page.getByLabel("Calling number", { exact: true }).fill("00010000001");
  await page.getByLabel("Issue details", { exact: true }).fill("Draft in newly created workspace");
  await page.getByLabel("Workspace", { exact: true }).selectOption({ label: "Training" });
  await page.getByLabel("Calling number", { exact: true }).waitFor();
  await page.waitForFunction(() => document.querySelector('input[aria-label="Calling number"]')?.value === "" || [...document.querySelectorAll('label')].some(x => x.textContent.includes("Calling number") && x.querySelector('input')?.value === ""));
  assert.equal(await page.getByLabel("Issue details", { exact: true }).inputValue(), "");
  await page.getByRole("button", { name: "Settings", exact: true }).click();
  await page.getByRole("heading", { name: "Administration · Training", exact: true }).waitFor();
  assert.equal(new URL(page.url()).pathname, "/dashboard/crm/settings");
  await page.reload();
  await page.getByRole("heading", { name: "Administration · Training", exact: true }).waitFor();
  await page.getByRole("button", { name: "Reports", exact: true }).click();
  assert.equal(new URL(page.url()).searchParams.get("view"), "reports");
  await page.goBack();
  await page.getByRole("heading", { name: "Settings", exact: true }).waitFor();
  await page.screenshot({ path: ".crm-test/workspace-settings.png", fullPage: true });
  await browser.close();
  console.log("PASS: one workspace selector creates/selects the batch, 100 profiles, selection persists across pages/reload, drafts reset on batch change, Settings and work URLs/back navigation stay in sync.");
})().catch((e) => { console.error(e.message); process.exit(1); });
